const TODAY = '2026-11-13';

function buildStopsForRoute(
  routeCode: string,
  school: string,
  depTime: string,
  arrTime: string,
  estTime: string,
  studentCount: number,
  isCompleted: boolean,
  isDelayed: boolean
) {
  const s1 = Math.max(4, Math.round(studentCount * 0.3));
  const s2 = Math.max(4, Math.round(studentCount * 0.35));
  const s3 = Math.max(3, studentCount - s1 - s2);

  return [
    {
      id: `${routeCode}-st1`,
      name: `${routeCode} Stop 1 · Residential Collector`,
      scheduledTime: depTime,
      estimatedTime: depTime,
      studentsCount: s1,
      completed: isCompleted || !isDelayed,
    },
    {
      id: `${routeCode}-st2`,
      name: `${routeCode} Stop 2 · Community Commons`,
      scheduledTime: '07:45 AM',
      estimatedTime: isDelayed ? '07:54 AM' : '07:45 AM',
      studentsCount: s2,
      completed: isCompleted,
    },
    {
      id: `${routeCode}-st3`,
      name: `${routeCode} Stop 3 · Transit Connector`,
      scheduledTime: '07:56 AM',
      estimatedTime: isDelayed ? '08:08 AM' : '07:56 AM',
      studentsCount: s3,
      completed: isCompleted,
    },
    {
      id: `${routeCode}-st4`,
      name: `${school} Campus Bay`,
      scheduledTime: arrTime,
      estimatedTime: estTime,
      studentsCount: 0,
      completed: isCompleted,
    },
  ];
}

